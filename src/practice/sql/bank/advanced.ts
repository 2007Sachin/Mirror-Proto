// New session starts at a user's first event or after more than 1800 seconds. Whole seconds avoid float error at exactly 30 minutes.
const NS = `CASE WHEN LAG(ts) OVER (PARTITION BY user_id ORDER BY ts) IS NULL OR strftime('%s', ts) - strftime('%s', LAG(ts) OVER (PARTITION BY user_id ORDER BY ts)) > 1800 THEN 1 ELSE 0 END`
const SESS = `WITH f AS (SELECT id, user_id, ts, ${NS} AS ns FROM activity), s AS (SELECT id, user_id, ts, SUM(ns) OVER (PARTITION BY user_id ORDER BY ts) AS sn FROM f)`

